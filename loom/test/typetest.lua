-- Real-keyboard check for run.ps1: a field at (7,2) that writes its submitted text to /home/typetest.txt.
local loom = require("loom")
local gui = loom.widget
local root = gui.Frame()
root:backgroundColor(0)
gui.TextLabel(root, 1, 2, "Name:")
local field = gui.TextInput(root, 7, 2, "")
field:size(20, 1)
field:backgroundColor(0x113355)
field:on("submit", function(_, text)
    local f = io.open("/home/typetest.txt", "w")
    f:write(text)
    f:close()
    loom.stop()
end)
loom.run(root)
root:Destroy()
require("term").clear()
print("typetest done")
